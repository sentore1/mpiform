"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import type { Form, FormField } from "@/types";
import { SYSTEM_FIELD_IDS } from "@/types";
import { createSubmission, uploadFile } from "@/lib/db";
import { Button } from "@/components/ui/Button";
import { Input } from "@/components/ui/Input";
import { Textarea } from "@/components/ui/Textarea";

interface FormFillerProps {
  form: Form;
}

const SYSTEM_IDS = new Set(Object.values(SYSTEM_FIELD_IDS));

export function FormFiller({ form }: FormFillerProps) {
  const router = useRouter();
  const [values, setValues] = useState<Record<string, string | string[]>>({});
  const [fileUploads, setFileUploads] = useState<Record<string, File>>({});
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [submitting, setSubmitting] = useState(false);
  const [submitted, setSubmitted] = useState(false);

  // Split into identity fields (always first) and custom fields
  const systemFields = form.fields.filter((f) => SYSTEM_IDS.has(f.id as never));
  const customFields = form.fields.filter((f) => !SYSTEM_IDS.has(f.id as never));

  function setValue(fieldId: string, value: string | string[]) {
    setValues((prev) => ({ ...prev, [fieldId]: value }));
    if (errors[fieldId]) setErrors((prev) => ({ ...prev, [fieldId]: "" }));
  }

  function toggleCheckbox(fieldId: string, optionValue: string) {
    const current = (values[fieldId] as string[]) ?? [];
    const updated = current.includes(optionValue)
      ? current.filter((v) => v !== optionValue)
      : [...current, optionValue];
    setValue(fieldId, updated);
  }

  function validate(): boolean {
    const newErrors: Record<string, string> = {};
    for (const field of form.fields) {
      if (!field.required) continue;
      const val = values[field.id];
      if (field.type === "checkbox" ? !(val as string[])?.length : !val || val === "") {
        if (field.type !== "file" && field.type !== "image") {
          newErrors[field.id] = `${field.label} is required`;
        } else if (!fileUploads[field.id]) {
          newErrors[field.id] = `${field.label} is required`;
        }
      }
    }
    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!validate()) return;
    setSubmitting(true);
    try {
      const finalValues: Record<string, string | string[] | null> = { ...values };
      for (const [fieldId, file] of Object.entries(fileUploads)) {
        const ext = file.name.split(".").pop();
        const path = `submissions/${form.id}/${Date.now()}-${fieldId}.${ext}`;
        const url = await uploadFile("uploads", path, file);
        finalValues[fieldId] = url;
      }
      const submission = await createSubmission(form.id, finalValues);
      void submission; // stored in DB, admin handles certificate
      setSubmitted(true);
    } finally {
      setSubmitting(false);
    }
  }

  // ── Success state ─────────────────────────────────────────────────────────
  if (submitted) {
    const submitterName = values[SYSTEM_FIELD_IDS.name] as string | undefined;
    return (
      <div className="flex flex-col items-center gap-6 py-12">
        <div className="w-16 h-16 rounded-full bg-green-500 flex items-center justify-center">
          <svg className="w-8 h-8 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
          </svg>
        </div>
        <div className="text-center">
          <h2 className="text-2xl font-bold text-gray-900">
            {submitterName ? `Thank you, ${submitterName}!` : "Form Submitted!"}
          </h2>
          <p className="text-gray-500 mt-2">Your response has been recorded successfully.</p>
        </div>
        {/* Certificate is generated by admin — not shown to users */}
        <Button variant="ghost" onClick={() => router.push("/")}>
          Back to Forms
        </Button>
      </div>
    );
  }

  // ── Form ──────────────────────────────────────────────────────────────────
  return (
    <form onSubmit={handleSubmit} noValidate className="flex flex-col gap-6">

      {/* Identity section — Name, Email, Phone always first */}
      {systemFields.length > 0 && (
        <div className="flex flex-col gap-4">
          <div className="flex items-center gap-2">
            <span className="text-xs font-semibold text-gray-500 uppercase tracking-wide">
              Your Details
            </span>
            <div className="flex-1 h-px bg-gray-100" />
          </div>
          {systemFields.map((field) => (
            <FieldInput
              key={field.id}
              field={field}
              value={values[field.id]}
              fileValue={fileUploads[field.id]}
              error={errors[field.id]}
              onChange={(val) => setValue(field.id, val)}
              onFileChange={(file) => {
                setFileUploads((prev) => ({ ...prev, [field.id]: file }));
                if (errors[field.id]) setErrors((prev) => ({ ...prev, [field.id]: "" }));
              }}
              onCheckboxToggle={(opt) => toggleCheckbox(field.id, opt)}
            />
          ))}
        </div>
      )}

      {/* Custom fields */}
      {customFields.length > 0 && (
        <div className="flex flex-col gap-4">
          {systemFields.length > 0 && (
            <div className="flex items-center gap-2">
              <span className="text-xs font-semibold text-gray-500 uppercase tracking-wide">
                Form Fields
              </span>
              <div className="flex-1 h-px bg-gray-100" />
            </div>
          )}
          {customFields.map((field) => (
            <FieldInput
              key={field.id}
              field={field}
              value={values[field.id]}
              fileValue={fileUploads[field.id]}
              error={errors[field.id]}
              onChange={(val) => setValue(field.id, val)}
              onFileChange={(file) => {
                setFileUploads((prev) => ({ ...prev, [field.id]: file }));
                if (errors[field.id]) setErrors((prev) => ({ ...prev, [field.id]: "" }));
              }}
              onCheckboxToggle={(opt) => toggleCheckbox(field.id, opt)}
            />
          ))}
        </div>
      )}

      <div className="pt-2 border-t border-gray-100">
        <Button
          type="submit"
          loading={submitting}
          className="w-full sm:w-auto bg-black hover:bg-gray-900 border-black focus:ring-gray-800"
        >
          Submit Form
        </Button>
      </div>
    </form>
  );
}

// ─── Individual field renderer ────────────────────────────────────────────────

interface FieldInputProps {
  field: FormField;
  value: string | string[] | undefined;
  fileValue?: File;
  error?: string;
  onChange: (val: string) => void;
  onFileChange: (file: File) => void;
  onCheckboxToggle: (optValue: string) => void;
}

function FieldInput({ field, value, fileValue, error, onChange, onFileChange, onCheckboxToggle }: FieldInputProps) {
  const stringVal = typeof value === "string" ? value : "";
  const arrayVal = Array.isArray(value) ? value : [];

  switch (field.type) {
    case "textarea":
      return (
        <Textarea
          label={field.label}
          placeholder={field.placeholder}
          required={field.required}
          value={stringVal}
          onChange={(e) => onChange(e.target.value)}
          error={error}
        />
      );

    case "select":
      return (
        <div className="flex flex-col gap-1 w-full">
          <label className="text-sm font-medium text-gray-700">
            {field.label}
            {field.required && <span className="text-red-500 ml-1">*</span>}
          </label>
          <select
            className={`w-full rounded-md border px-3 py-2 text-sm bg-white focus:outline-none focus:ring-2 focus:ring-indigo-500 ${error ? "border-red-500" : "border-gray-300"}`}
            value={stringVal}
            onChange={(e) => onChange(e.target.value)}
            required={field.required}
          >
            <option value="">Select an option…</option>
            {(field.options ?? []).map((o) => (
              <option key={o.value} value={o.value}>{o.label}</option>
            ))}
          </select>
          {error && <p className="text-xs text-red-600">{error}</p>}
        </div>
      );

    case "radio":
      return (
        <fieldset className="flex flex-col gap-2">
          <legend className="text-sm font-medium text-gray-700">
            {field.label}
            {field.required && <span className="text-red-500 ml-1">*</span>}
          </legend>
          {(field.options ?? []).map((o) => (
            <label key={o.value} className="flex items-center gap-2 cursor-pointer">
              <input type="radio" name={field.id} value={o.value} checked={stringVal === o.value} onChange={() => onChange(o.value)} className="accent-indigo-600" />
              <span className="text-sm text-gray-700">{o.label}</span>
            </label>
          ))}
          {error && <p className="text-xs text-red-600">{error}</p>}
        </fieldset>
      );

    case "checkbox":
      return (
        <fieldset className="flex flex-col gap-2">
          <legend className="text-sm font-medium text-gray-700">
            {field.label}
            {field.required && <span className="text-red-500 ml-1">*</span>}
          </legend>
          {(field.options ?? []).map((o) => (
            <label key={o.value} className="flex items-center gap-2 cursor-pointer">
              <input type="checkbox" value={o.value} checked={arrayVal.includes(o.value)} onChange={() => onCheckboxToggle(o.value)} className="accent-indigo-600" />
              <span className="text-sm text-gray-700">{o.label}</span>
            </label>
          ))}
          {error && <p className="text-xs text-red-600">{error}</p>}
        </fieldset>
      );

    case "file":
    case "image":
      return (
        <div className="flex flex-col gap-1 w-full">
          <label className="text-sm font-medium text-gray-700">
            {field.label}
            {field.required && <span className="text-red-500 ml-1">*</span>}
          </label>
          <div className={`relative rounded-lg border-2 border-dashed p-6 flex flex-col items-center gap-2 text-gray-400 ${error ? "border-red-400" : "border-gray-300"}`}>
            <input
              type="file"
              accept={field.accept ?? (field.type === "image" ? "image/*" : undefined)}
              onChange={(e) => { const f = e.target.files?.[0]; if (f) onFileChange(f); }}
              className="absolute inset-0 w-full h-full opacity-0 cursor-pointer"
              aria-label={field.label}
            />
            {fileValue ? (
              <>
                {field.type === "image" && (
                  // eslint-disable-next-line @next/next/no-img-element
                  <img src={URL.createObjectURL(fileValue)} alt="Preview" className="max-h-32 rounded object-contain" />
                )}
                <p className="text-sm text-indigo-600 font-medium">{fileValue.name}</p>
                <p className="text-xs">Click to change</p>
              </>
            ) : (
              <>
                <svg className="w-8 h-8" fill="none" viewBox="0 0 24 24" stroke="currentColor" aria-hidden="true">
                  <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={1.5} d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-8l-4-4m0 0L8 8m4-4v12" />
                </svg>
                <p className="text-sm">{field.type === "image" ? "Click or drag an image to upload" : "Click or drag a file to upload"}</p>
                {field.accept && <p className="text-xs">Accepted: {field.accept}</p>}
              </>
            )}
          </div>
          {error && <p className="text-xs text-red-600">{error}</p>}
        </div>
      );

    default:
      return (
        <Input
          label={field.label}
          type={field.type}
          placeholder={field.placeholder}
          required={field.required}
          value={stringVal}
          onChange={(e) => onChange(e.target.value)}
          error={error}
        />
      );
  }
}
